"""Measured input data for the case study (City of Zurich, 2015-2021).

Source
------
``data/zurich_electricity_consumption.csv`` is the dataset distributed with the
darts library (https://github.com/unit8co/darts, file
datasets/zurich_electricity_consumption.csv, MD5 764bdd3bb4f9066ba7523accf9089505).
It combines two open-government datasets of the City of Zurich:

* ewz "Stromabgabe nach Netzebenen": metered 15-min electricity delivered at
  low voltage (households and small businesses, column Value_NE5, kWh per 15 min);
* UGZ "Meteodaten Stundenmittelwerte", station Zch_Stampfenbachstrasse: hourly
  means of global horizontal irradiance (StrGlo), air temperature (T) and scalar
  wind speed (WVs), resampled to 15 min and interpolated by the darts authors.

Time stamps are UTC. The hourly weather means are stamped at the start of the
hour; after linear interpolation this shifts the irradiance curve 30 min early
relative to solar noon, which is corrected here (+30 min). Everything is then
expressed in local standard time (CET, UTC+1), which defines the tariff periods.

Load models
-----------
* ``stochastic`` (baseline): a neighbourhood of 14 apartments simulated with the
  validated bottom-up model of Richardson et al. (2010) as implemented in
  richardsonpy, driven by the Zurich irradiance; generated by
  ``src/gen_household_load.py`` and cached in ``data/household_load_15min.csv``.
* ``h0``: BDEW H0 standard residential load profile (demandlib), per calendar year.
* ``metered``: the metered Zurich low-voltage aggregate (Value_NE5).
All three are scaled to the same mean annual demand (55,370 kWh, mean 6.32 kW).
"""
from __future__ import annotations

import os
import warnings

import numpy as np
import pandas as pd

warnings.filterwarnings("ignore", category=FutureWarning)

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "data")
ZURICH_CSV = os.path.join(DATA, "zurich_electricity_consumption.csv")
ZURICH_MD5 = "764bdd3bb4f9066ba7523accf9089505"
HOUSEHOLD_CSV = os.path.join(DATA, "household_load_15min.csv")

SITE = {"latitude": 47.3868, "longitude": 8.5398, "altitude": 408.0, "name": "Zurich Stampfenbachstrasse"}
YEARS = list(range(2015, 2022))           # complete calendar years
TRAIN_YEARS = [2015, 2016, 2017]          # rule-threshold tuning
TEST_YEARS = [2018, 2019, 2020, 2021]     # all reported decision results

CONFIG = {
    "annual_demand_kwh": 55_370.0,
    "pv_kwp": 20.0, "pv_tilt": 30.0, "pv_azimuth": 180.0, "pv_gamma": -0.004,
    "wind_rated_kw": 5.0, "wind_hub_m": 20.0, "wind_ref_m": 10.0, "wind_shear": 1.0 / 7.0,
    "wind_cut_in": 3.0, "wind_rated_ms": 11.0, "wind_cut_out": 25.0,
    "periods": {"t1_offpeak": (23, 7), "t2_midpeak": (7, 17), "t3_onpeak": (17, 23)},
    "prices": {"t1_offpeak": 0.10, "t2_midpeak": 0.15, "t3_onpeak": 0.30},
}
PERIODS = ["t1_offpeak", "t2_midpeak", "t3_onpeak"]
PERIOD_HOURS = np.array([8.0, 10.0, 6.0])


def md5(path):
    import hashlib
    h = hashlib.md5()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def period_of_hour(hour):
    hour = np.asarray(hour)
    return np.where((hour >= 23) | (hour < 7), "t1_offpeak", np.where(hour < 17, "t2_midpeak", "t3_onpeak"))


_RAW = None


def zurich_raw() -> pd.DataFrame:
    """Measured series on a 15-min grid in local standard time (CET)."""
    global _RAW
    if _RAW is not None:
        return _RAW
    if md5(ZURICH_CSV) != ZURICH_MD5:
        raise RuntimeError("Zurich data file does not match the published checksum")
    df = pd.read_csv(ZURICH_CSV, parse_dates=["Timestamp"], index_col="Timestamp")
    wx = df[["StrGlo [W/m2]", "T [°C]", "WVs [m/s]"]].copy()
    wx.index = wx.index + pd.Timedelta(minutes=30)            # hour-start stamp -> centred
    grid = df.index
    wx = wx.reindex(grid.union(wx.index)).interpolate(limit_direction="both").reindex(grid)
    out = pd.DataFrame({"ghi": wx["StrGlo [W/m2]"].clip(lower=0).to_numpy(),
                        "temp_air": wx["T [°C]"].to_numpy(),
                        "wind_ms": wx["WVs [m/s]"].clip(lower=0).to_numpy(),
                        "lv_kw": (df["Value_NE5"] / 0.25).to_numpy()}, index=grid + pd.Timedelta(hours=1))
    full = pd.date_range(f"{YEARS[0]}-01-01 00:00", f"{YEARS[-1]}-12-31 23:45", freq="15min")
    out = out.reindex(full).bfill()                             # first CET hour of 2015 (night)
    out.index.name = "Timestamp"
    _RAW = out
    return out



def _import_pvlib():
    """Import pvlib even when its optional h5py dependency cannot be loaded.

    pvlib imports h5py at start-up only for the Linke-turbidity lookup in pvlib.clearsky, which this
    study does not use. On some Windows machines the h5py DLL is missing or blocked by an application
    control policy ("DLL load failed while importing h5"). In that case a placeholder module is
    registered so that pvlib loads; the functions used here (solar position, Erbs, Hay-Davies, SAPM cell
    temperature, PVWatts) do not touch h5py, so the results are unchanged.
    """
    import sys
    import types
    try:
        import pvlib
        return pvlib
    except ImportError as err:
        if "h5" not in str(err) and "h5py" not in repr(getattr(err, "name", "")):
            raise
        for name in [m for m in sys.modules if m == "pvlib" or m.startswith("pvlib.") or m == "h5py" or m.startswith("h5py.")]:
            del sys.modules[name]
        stub = types.ModuleType("h5py")
        stub.__doc__ = "placeholder: h5py could not be loaded; only pvlib's Linke-turbidity lookup needs it"
        sys.modules["h5py"] = stub
        import pvlib
        return pvlib

def solar_components(raw: pd.DataFrame) -> pd.DataFrame:
    """Erbs decomposition of measured GHI and transposition to the array plane."""
    pvlib = _import_pvlib()
    mid = raw.index + pd.Timedelta(minutes=7.5)
    tz_idx = mid.tz_localize("Etc/GMT-1")                          # CET without DST
    sol = pvlib.solarposition.get_solarposition(tz_idx, SITE["latitude"], SITE["longitude"], SITE["altitude"],
                                                temperature=raw["temp_air"].to_numpy())
    dni_extra = pvlib.irradiance.get_extra_radiation(tz_idx).to_numpy()
    zen = sol["zenith"].to_numpy()
    ghi = np.where(zen >= 90, 0.0, raw["ghi"].to_numpy())
    erbs = pvlib.irradiance.erbs(ghi, zen, tz_idx.dayofyear)
    dni = np.nan_to_num(np.asarray(erbs["dni"], float)).clip(min=0)
    dhi = np.nan_to_num(np.asarray(erbs["dhi"], float)).clip(min=0)
    night = zen >= 90
    dni[night] = 0.0; dhi[night] = 0.0
    poa = pvlib.irradiance.get_total_irradiance(CONFIG["pv_tilt"], CONFIG["pv_azimuth"],
                                                sol["apparent_zenith"].to_numpy(), sol["azimuth"].to_numpy(),
                                                dni, ghi, dhi, dni_extra=dni_extra, model="haydavies")
    poa_g = np.nan_to_num(np.asarray(poa["poa_global"], float)).clip(min=0)
    direct_h = (ghi - dhi).clip(min=0)
    return pd.DataFrame({"poa": poa_g, "dni": dni, "dhi": dhi, "direct_h": direct_h, "zenith": zen},
                        index=raw.index)


def pv_wind(raw: pd.DataFrame, pv_scale=1.0, wind_scale=1.0) -> pd.DataFrame:
    pvlib = _import_pvlib()
    comp = solar_components(raw)
    tp = pvlib.temperature.TEMPERATURE_MODEL_PARAMETERS["sapm"]["open_rack_glass_glass"]
    tcell = pvlib.temperature.sapm_cell(comp["poa"].to_numpy(), raw["temp_air"].to_numpy(),
                                        raw["wind_ms"].to_numpy(), **tp)
    pdc0 = CONFIG["pv_kwp"] * 1000.0
    pdc = pvlib.pvsystem.pvwatts_dc(comp["poa"].to_numpy(), tcell, pdc0, CONFIG["pv_gamma"])
    loss = pvlib.pvsystem.pvwatts_losses() / 100.0
    pac = pvlib.inverter.pvwatts(np.asarray(pdc) * (1 - loss), pdc0 / 0.96)
    pv_kw = np.clip(np.nan_to_num(np.asarray(pac, float)), 0, None) / 1000.0
    v = raw["wind_ms"].to_numpy() * (CONFIG["wind_hub_m"] / CONFIG["wind_ref_m"]) ** CONFIG["wind_shear"]
    ci, vr, co, pr = CONFIG["wind_cut_in"], CONFIG["wind_rated_ms"], CONFIG["wind_cut_out"], CONFIG["wind_rated_kw"]
    wind_kw = np.where((v < ci) | (v > co), 0.0, np.where(v < vr, pr * (v ** 3 - ci ** 3) / (vr ** 3 - ci ** 3), pr))
    return pd.DataFrame({"pv_kw": pv_kw * pv_scale, "wind_kw": wind_kw * wind_scale}, index=raw.index)


def _scale_to_demand(s: pd.Series) -> pd.Series:
    yrs = s.index.year
    annual = s.groupby(yrs).sum() * 0.25
    return s * (CONFIG["annual_demand_kwh"] / annual.loc[YEARS].mean())


def load_series(model="stochastic") -> pd.Series:
    raw = zurich_raw()
    if model == "metered":
        s = raw["lv_kw"].copy()
    elif model == "h0":
        import demandlib.bdew as bdew
        parts = []
        for y in YEARS:
            p = bdew.ElecSlp(y).get_scaled_power_profiles({"h0": 1000.0})["h0"]
            p.index = pd.DatetimeIndex(p.index).tz_localize(None)
            parts.append(p)
        s = pd.concat(parts).reindex(raw.index).ffill().bfill()
    elif model == "stochastic":
        if not os.path.exists(HOUSEHOLD_CSV):
            raise FileNotFoundError("run src/gen_household_load.py first")
        hh = pd.read_csv(HOUSEHOLD_CSV, parse_dates=["Timestamp"], index_col="Timestamp")["load_kw"]
        s = hh.reindex(raw.index)
    else:
        raise ValueError(model)
    return _scale_to_demand(s.astype(float))


def build_inputs(pv_scale=1.0, wind_scale=1.0, load_model="stochastic", years=None, prices=None) -> pd.DataFrame:
    raw = zurich_raw()
    gen = pv_wind(raw, pv_scale, wind_scale)
    df = pd.DataFrame({"load_kw": load_series(load_model).to_numpy(), "pv_kw": gen["pv_kw"].to_numpy(),
                       "wind_kw": gen["wind_kw"].to_numpy(), "ghi": raw["ghi"].to_numpy(),
                       "temp_air": raw["temp_air"].to_numpy()}, index=raw.index)
    if years is not None:
        df = df[df.index.year.isin(years)]
    df["hour"] = df.index.hour
    df["date"] = df.index.normalize()
    df["period"] = period_of_hour(df["hour"].to_numpy())
    pr = prices or CONFIG["prices"]
    df["price"] = df["period"].map(pr).astype(float)
    return df


def diagnostics(df: pd.DataFrame) -> dict:
    hourly = df.groupby("hour")[["load_kw", "pv_kw", "wind_kw", "price"]].mean()
    acf = {c: {lag: float(df[c].autocorr(lag)) for lag in (1, 4, 96)} for c in ["load_kw", "pv_kw", "wind_kw"]}
    per = df.groupby("period")[["load_kw", "pv_kw", "wind_kw"]].mean()
    yrs = df.index.year
    annual = pd.DataFrame({"load_kwh": df.load_kw.groupby(yrs).sum() * 0.25,
                           "pv_kwh": df.pv_kw.groupby(yrs).sum() * 0.25,
                           "wind_kwh": df.wind_kw.groupby(yrs).sum() * 0.25,
                           "ghi_kwh_m2": df.ghi.groupby(yrs).sum() * 0.25 / 1000})
    daily = df.load_kw.resample("D").sum() * 0.25
    dd = pd.DataFrame({"kwh": daily}); dd["m"] = dd.index.month; dd["wd"] = dd.index.dayofweek; dd["y"] = dd.index.year
    resid = dd.kwh - dd.groupby(["y", "m", "wd"]).kwh.transform("mean")
    return {"hourly": hourly, "acf": acf, "period_means": per, "annual": annual,
            "daily_cv": float(daily.std() / daily.mean()),
            "daily_resid_cv": float(resid.std() / daily.mean()),
            "pv_night_share": float((df.loc[df.hour < 4, "pv_kw"] > 1e-6).mean())}


